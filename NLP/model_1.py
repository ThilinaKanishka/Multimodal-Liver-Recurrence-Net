def extract_entities_batch(notes, ner_pipe):
    results = []
    for i, note in enumerate(notes):
        ents = ner_pipe(note)
        results.append('; '.join(f"{e['word']}:{e['entity_group']}" for e in ents))
        if i % 200 == 0:
            print(f'  NER on {i}/{len(notes)}', end='\r')
    print()
    return results

