import torch.nn as nn
from torch.utils.data import Dataset, DataLoader

class NotesDataset(Dataset):
    def __init__(self, texts, labels, tokenizer, max_len):
        self.texts = texts
        self.labels = labels
        self.tokenizer = tokenizer
        self.max_len = max_len

    def __len__(self):
        return len(self.texts)

    def __getitem__(self, idx):
        enc = self.tokenizer(
            str(self.texts[idx]), padding='max_length', truncation=True,
            max_length=self.max_len, return_tensors='pt',
        )
        return {
            'input_ids': enc['input_ids'].squeeze(0),
            'attention_mask': enc['attention_mask'].squeeze(0),
            'labels': torch.tensor(self.labels[idx], dtype=torch.long),
        }

train_ds = NotesDataset(X_train, y_train, tokenizer, MAX_LEN)
val_ds = NotesDataset(X_val, y_val, tokenizer, MAX_LEN)
test_ds = NotesDataset(X_test, y_test, tokenizer, MAX_LEN)

train_loader = DataLoader(train_ds, batch_size=BATCH_SIZE, shuffle=True)
val_loader = DataLoader(val_ds, batch_size=BATCH_SIZE)
test_loader = DataLoader(test_ds, batch_size=BATCH_SIZE)

print(f'Train batches: {len(train_loader)}, Val batches: {len(val_loader)}, Test batches: {len(test_loader)}')

from transformers import AutoModelForSequenceClassification, get_linear_schedule_with_warmup
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, confusion_matrix, classification_report

finetune_model = AutoModelForSequenceClassification.from_pretrained(
    MODEL_NAME, num_labels=2
).to(device)

EPOCHS = 3
optimizer = torch.optim.AdamW(finetune_model.parameters(), lr=2e-5)
total_steps = len(train_loader) * EPOCHS
scheduler = get_linear_schedule_with_warmup(optimizer, num_warmup_steps=0, num_training_steps=total_steps)

for epoch in range(EPOCHS):
    finetune_model.train()
    total_loss = 0
    for batch in train_loader:
        optimizer.zero_grad()
        input_ids = batch['input_ids'].to(device)
        attention_mask = batch['attention_mask'].to(device)
        labels_batch = batch['labels'].to(device)

        outputs = finetune_model(input_ids=input_ids, attention_mask=attention_mask, labels=labels_batch)
        loss = outputs.loss
        loss.backward()
        torch.nn.utils.clip_grad_norm_(finetune_model.parameters(), 1.0)
        optimizer.step()
        scheduler.step()
        total_loss += loss.item()

    avg_loss = total_loss / len(train_loader)

    finetune_model.eval()
    val_preds_ft, val_true_ft = [], []
    with torch.no_grad():
        for batch in val_loader:
            input_ids = batch['input_ids'].to(device)
            attention_mask = batch['attention_mask'].to(device)
            outputs = finetune_model(input_ids=input_ids, attention_mask=attention_mask)
            preds = torch.argmax(outputs.logits, dim=1).cpu().numpy()
            val_preds_ft.extend(preds)
            val_true_ft.extend(batch['labels'].numpy())

    val_acc = accuracy_score(val_true_ft, val_preds_ft)
    print(f'Epoch {epoch+1}/{EPOCHS} | train loss: {avg_loss:.4f} | val accuracy: {val_acc:.3f}')

finetune_model.eval()
test_preds_ft, test_true_ft = [], []
with torch.no_grad():
    for batch in test_loader:
        input_ids = batch['input_ids'].to(device)
        attention_mask = batch['attention_mask'].to(device)
        outputs = finetune_model(input_ids=input_ids, attention_mask=attention_mask)
        preds = torch.argmax(outputs.logits, dim=1).cpu().numpy()
        test_preds_ft.extend(preds)
        test_true_ft.extend(batch['labels'].numpy())

print('=== Fine-Tuned Model: Test Set Results ===')
print(f'Accuracy:  {accuracy_score(test_true_ft, test_preds_ft):.3f}')
print(f'Precision: {precision_score(test_true_ft, test_preds_ft):.3f}')
print(f'Recall:    {recall_score(test_true_ft, test_preds_ft):.3f}')
print(f'F1 score:  {f1_score(test_true_ft, test_preds_ft):.3f}')
print('\nConfusion matrix:')
print(confusion_matrix(test_true_ft, test_preds_ft))
print()
print(classification_report(test_true_ft, test_preds_ft, target_names=['No cancer', 'Cancer']))

