def extract_embeddings(texts, tokenizer, model, device):
    all_embeddings = []
    with torch.no_grad():
        for i in range(0, len(texts), BATCH_SIZE):
            batch = list(texts[i:i + BATCH_SIZE])
            enc = tokenizer(batch, padding=True, truncation=True, max_length=MAX_LEN, return_tensors='pt').to(device)
            out = model(**enc)
            cls_embeddings = out.last_hidden_state[:, 0, :]
            all_embeddings.append(cls_embeddings.cpu().numpy())
            print(f'  embedded {min(i + BATCH_SIZE, len(texts))}/{len(texts)}', end='\r')
    print()
    return np.vstack(all_embeddings)

